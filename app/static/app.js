const $ = (id) => document.getElementById(id);
let reportId = null;
function showFile(input, target) {
  const file = input.files[0];
  $(target).textContent = file ? file.name : "No file selected";
  input.closest(".dropzone").classList.toggle("selected", Boolean(file));
  $("analyze").disabled = !$("dataset").files.length;
}
$("dataset").addEventListener("change", () => showFile($("dataset"), "dataset-name"));
$("metadata").addEventListener("change", () => showFile($("metadata"), "metadata-name"));
for (const [input, target] of [["dataset","dataset-name"],["metadata","metadata-name"]]) {
  const zone = $(input).closest(".dropzone");
  zone.addEventListener("dragover", e => {e.preventDefault(); zone.classList.add("dragging");});
  zone.addEventListener("dragleave", () => zone.classList.remove("dragging"));
  zone.addEventListener("drop", e => {
    e.preventDefault();
    zone.classList.remove("dragging");
    if (e.dataTransfer.files.length) {
      const dt = new DataTransfer(); dt.items.add(e.dataTransfer.files[0]); $(input).files = dt.files;
      showFile($(input), target);
    }
  });
}
function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
}
function cell(value) { return `<td>${escapeHtml(value === null || value === undefined ? "—" : value)}</td>`; }
function sourceLabel(value) {
  return ({user_supplied:"User supplied", system_generated:"Auto-generated", ai_generated:"AI generated"})[value] || "Auto-generated";
}
$("analyze").addEventListener("click", async () => {
  $("error").classList.add("hidden"); $("loading").classList.remove("hidden");
  $("analyze").disabled = true;
  const form = new FormData(); form.append("dataset", $("dataset").files[0]);
  if ($("metadata").files[0]) form.append("metadata", $("metadata").files[0]);
  try {
    const response = await fetch("/api/analyze", {method:"POST", body:form});
    const result = await response.json();
    if (!response.ok) throw new Error(result.detail || "Analysis failed.");
    render(result);
  } catch (err) {
    $("error").textContent = err.message; $("error").classList.remove("hidden");
  } finally {
    $("loading").classList.add("hidden"); $("analyze").disabled = !$("dataset").files.length;
  }
});
function render(r) {
  reportId = r.report_id;
  setDownloadLinks("dict");
  setDownloadLinks("missing");
  $("m-rows").textContent = Number(r.summary.rows).toLocaleString();
  $("m-cols").textContent = r.summary.columns;
  $("m-nulls").textContent = Number(r.summary.total_missing_cells).toLocaleString();
  $("m-gaps").textContent = r.missing_metadata.length;
  $("ai-status").textContent = r.ai_status;
  const described = r.dictionary.filter(x => Boolean(x.description)).length;
  const aiGenerated = r.dictionary.filter(x => x.description_source === "ai_generated").length;
  const systemGenerated = r.dictionary.filter(x => x.description_source === "system_generated").length;
  const gaps = r.missing_metadata.length;
  const duplicates = Number(r.summary.duplicate_rows || 0);
  $("s-described").textContent = `${described}/${r.summary.columns}`;
  $("s-ai").textContent = aiGenerated.toLocaleString();
  $("s-gaps").textContent = gaps.toLocaleString();
  $("s-duplicates").textContent = duplicates.toLocaleString();
  $("s-missing-values").textContent = Number(r.summary.total_missing_cells || 0).toLocaleString();
  const summaryParts = [
    `The dataset contains ${Number(r.summary.rows).toLocaleString()} records across ${r.summary.columns} features.`,
    `${described} of ${r.summary.columns} features have descriptions${aiGenerated ? `, including ${aiGenerated} generated by AI` : ""}${systemGenerated ? `${aiGenerated ? " and " : ", with "}${systemGenerated} generated automatically by the system` : ""}.`,
    gaps ? `${gaps} metadata item${gaps === 1 ? " needs" : "s need"} review.` : "No metadata gaps were identified by the current checks.",
    `${Number(r.summary.total_missing_cells || 0).toLocaleString()} missing data cells and ${duplicates.toLocaleString()} duplicate rows were detected.`
  ];
  $("report-summary-text").textContent = summaryParts.join(" ");
  $("dictionary-body").innerHTML = r.dictionary.map(x => `<tr>${cell(x.feature)}${cell(x.data_type)}${cell(x.description)}${cell(sourceLabel(x.description_source))}${cell(x.unit || "Not supplied")}${cell(x.measurement_range || "Not supplied")}${cell(x.min)}${cell(x.max)}${cell(x.mean)}${cell(x.std)}${cell(x.non_numeric_count)}${cell(x.outlier_count_iqr)}${cell(x.null_percent + "%")}<td><span class="pill ${x.completeness==="Complete"?"good":""}">${escapeHtml(x.completeness)}</span></td></tr>`).join("");
  $("missing-body").innerHTML = r.missing_metadata.length ? r.missing_metadata.map(x => `<tr>${cell(x.feature)}${cell(x.missing_field)}${cell(x.reason)}</tr>`).join("") : '<tr><td colspan="3">No missing metadata identified by the current rules.</td></tr>';
  $("preview-head").innerHTML = `<tr>${r.preview_columns.map(x=>`<th>${escapeHtml(x)}</th>`).join("")}</tr>`;
  $("preview-body").innerHTML = r.preview.map(row => `<tr>${r.preview_columns.map(c=>cell(row[c])).join("")}</tr>`).join("");
  $("results").classList.remove("hidden");
  $("results").scrollIntoView({behavior:"smooth"});
}
function setDownloadLinks(kind) {
  for (const format of ["xlsx", "pdf"]) {
    const link = $(`download-${kind}-${format}`);
    link.href = reportId ? `/api/reports/${reportId}/${kind}/${format}` : "#";
  }
}
$("new-analysis").addEventListener("click", () => {
  $("dataset").value=""; $("metadata").value="";
  $("dataset-name").textContent="No dataset selected"; $("metadata-name").textContent="No metadata selected";
  document.querySelectorAll(".dropzone").forEach(zone => zone.classList.remove("selected","dragging"));
  $("analyze").disabled=true; $("results").classList.add("hidden"); $("upload").scrollIntoView({behavior:"smooth"});
});
