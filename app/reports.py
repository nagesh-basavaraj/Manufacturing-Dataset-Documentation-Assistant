from pathlib import Path
from uuid import uuid4
import pandas as pd
from . import config


def _safe_frame(rows, columns=None):
    frame = pd.DataFrame(rows, columns=columns)
    for col in frame.columns:
        def protect(value):
            if isinstance(value, str) and value.lstrip(" \t\r\n").startswith(("=", "+", "-", "@")):
                return "'" + value
            return value
        frame[col] = frame[col].map(protect)
    return frame


def _write_pdf(path: Path, title: str, frame: pd.DataFrame):
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

    doc = SimpleDocTemplate(str(path), pagesize=landscape(A4), rightMargin=12*mm,
                            leftMargin=12*mm, topMargin=12*mm, bottomMargin=12*mm)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("ReportTitle", parent=styles["Title"], alignment=TA_LEFT,
                                 textColor=colors.HexColor("#176f65"), fontSize=16, leading=20)
    cell_style = ParagraphStyle("Cell", parent=styles["BodyText"], fontSize=7, leading=9,
                                wordWrap="CJK")
    story = [Paragraph(title, title_style), Spacer(1, 5*mm),
             Paragraph(f"Generated by PS 192 Manufacturing Dataset Documentation Assistant · {len(frame)} entries", styles["Normal"]),
             Spacer(1, 4*mm)]
    headers = [Paragraph(str(c).replace("&", "&amp;"), cell_style) for c in frame.columns]
    data = [headers]
    for row in frame.fillna("").astype(str).itertuples(index=False, name=None):
        data.append([Paragraph(str(v).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"), cell_style) for v in row])
    available_width = landscape(A4)[0] - 24*mm
    widths = [available_width / max(1, len(frame.columns))] * len(frame.columns)
    table = Table(data, colWidths=widths, repeatRows=1, hAlign="LEFT")
    table.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#eaf5f1")),
        ("TEXTCOLOR", (0,0), (-1,0), colors.HexColor("#24534c")),
        ("GRID", (0,0), (-1,-1), 0.35, colors.HexColor("#dce8e3")),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("LEFTPADDING", (0,0), (-1,-1), 5), ("RIGHTPADDING", (0,0), (-1,-1), 5),
        ("TOPPADDING", (0,0), (-1,-1), 5), ("BOTTOMPADDING", (0,0), (-1,-1), 5),
    ]))
    story.append(table)
    doc.build(story)


def create_reports(dictionary: list[dict], missing: list[dict]) -> str:
    report_id = uuid4().hex
    folder = Path(config.REPORT_DIR)
    folder.mkdir(parents=True, exist_ok=True)
    dictionary_frame = _safe_frame(dictionary)
    missing_frame = _safe_frame(missing, columns=["feature", "missing_field", "reason"])
    dictionary_frame.to_excel(folder / f"{report_id}_dictionary.xlsx", index=False, engine="openpyxl")
    missing_frame.to_excel(folder / f"{report_id}_missing.xlsx", index=False, engine="openpyxl")
    _write_pdf(folder / f"{report_id}_dictionary.pdf", "Manufacturing Dataset · Data Dictionary", dictionary_frame)
    _write_pdf(folder / f"{report_id}_missing.pdf", "Manufacturing Dataset · Missing Metadata", missing_frame)
    return report_id


def report_path(report_id: str, kind: str, file_format: str = "xlsx") -> Path:
    if kind not in ("dictionary", "missing") or file_format not in ("xlsx", "pdf") or not report_id.isalnum() or len(report_id) != 32:
        raise ValueError("Invalid report reference.")
    path = Path(config.REPORT_DIR) / f"{report_id}_{kind}.{file_format}"
    if not path.is_file():
        raise FileNotFoundError("Report not found. Run analysis again.")
    return path
